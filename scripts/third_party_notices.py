"""Writes THIRD-PARTY-NOTICES.txt: the licences of every crate linked into rview.exe and of the
fonts embedded in it. Run it after changing dependencies (release.ps1 does); with
--check it only reports whether the committed file is out of date.

    python scripts/third_party_notices.py [--check]

Needs only Python 3 and cargo; the crate sources must be downloaded (any cargo build does it).
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
TARGET = "x86_64-pc-windows-msvc"
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE")
# Data files a crate embeds in the exe whose licences live outside the crate's root
EMBEDDED = {"epaint_default_fonts": "fonts"}


def cargo(*args: str) -> str:
    return subprocess.run(["cargo", "--color", "never", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def shipped() -> set[tuple[str, str]]:
    """(name, version) of every crate compiled into rview.exe (no build or dev dependencies)."""
    tree = cargo("tree", "-p", "rview", "-e", "normal", "--target", TARGET, "--prefix", "none", "--format", "{p}")
    crates = set()
    for line in tree.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v") and not line.rstrip().endswith(")"):
            crates.add((parts[0], parts[1][1:]))
    return crates


def read(path: Path) -> str:
    return path.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n").strip()


def licence_files(pkg: dict) -> list[Path]:
    root = Path(pkg["manifest_path"]).parent
    files = [p for p in root.iterdir() if p.is_file() and p.name.upper().startswith(LICENSE_PREFIXES)]
    if pkg.get("license_file"):
        files.append(root / pkg["license_file"])
    if pkg["name"] in EMBEDDED:
        files += (root / EMBEDDED[pkg["name"]]).glob("*.txt")
    return sorted({p.resolve() for p in files if p.is_file()}, key=lambda p: p.name.lower())


def render() -> str:
    meta = json.loads(cargo("metadata", "--format-version", "1", "--locked"))
    packages = {(p["name"], p["version"]): p for p in meta["packages"]}
    crates = sorted(shipped(), key=lambda c: (c[0].lower(), c[1]))

    texts: dict[str, list[str]] = {}
    without: list[str] = []
    rows = []
    for name, version in crates:
        pkg = packages[(name, version)]
        label = f"{name} {version}"
        rows.append(f"{label:<40} {pkg.get('license') or 'see licence file'}")
        files = licence_files(pkg)
        if not files:
            authors = ", ".join(pkg.get("authors") or []) or "its authors"
            without.append(f"{label}: {pkg.get('license')}, by {authors}")
        for f in files:
            texts.setdefault(read(f), []).append(f"{label} ({f.name})")

    out = [
        "rView third-party notices",
        "",
        "rview.exe contains the Rust crates listed below and embeds the Lato font and egui's default",
        "fonts. Their licences follow. rView itself is MIT licensed (LICENSE.md).",
        "Generated by scripts/third_party_notices.py; do not edit by hand.",
        "",
        "=" * 78,
        "Lato (embedded font, assets/fonts)",
        "=" * 78,
        "",
        read(ROOT / "assets" / "fonts" / "OFL.txt"),
        "",
        "=" * 78,
        f"Crates ({len(crates)})",
        "=" * 78,
        "",
        *rows,
    ]
    if without:
        out += [
            "",
            "Crates that ship no licence file: their terms are the SPDX licences named below, whose",
            "full texts appear further down for other crates.",
            "",
            *without,
        ]
    for text, users in texts.items():
        out += ["", "=" * 78, *users, "=" * 78, "", text]
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print(f"{OUT.name} is out of date: run python scripts/third_party_notices.py", file=sys.stderr)
            return 1
        print(f"{OUT.name} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(text) // 1024} KiB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
